"""Export editable Directorate logistics kits and shared loading components to glTF.

Requires numpy. Gameplay footprints, navigation, materials and vehicle sockets are
inputs to the dimensional contract, never generated by this exporter.
"""
import argparse
import copy
import hashlib
import importlib.util
import json
from pathlib import Path
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'assets/source/buildings/directorate'
FAMILIES = ('storage_depot', 'supply_depot', 'logistics_hub')
spec = importlib.util.spec_from_file_location('industrial_components', ROOT / 'build/Author-IndustrialBuildings.py')
components = importlib.util.module_from_spec(spec)
spec.loader.exec_module(components)


def roof(mesh, part):
    lo, hi = np.asarray(part['min']), np.asarray(part['max'])
    x = (lo[0] + hi[0]) / 2
    front = [[lo[0],lo[1],hi[2]],[hi[0],lo[1],hi[2]],[x,hi[1],hi[2]]]
    back = [[lo[0],lo[1],lo[2]],[hi[0],lo[1],lo[2]],[x,hi[1],lo[2]]]
    mesh.face(front,part['cell'],[0,0,1])
    mesh.face(back,part['cell'],[0,0,-1])
    mesh.face([front[0],back[0],back[2],front[2]],part['cell'],[-1,1,0])
    mesh.face([front[1],front[2],back[2],back[1]],part['cell'],[1,1,0])
    mesh.face([front[0],front[1],back[1],back[0]],part['cell'],[0,-1,0])


def resolve_parts(module, shared):
    if 'source' not in module:
        return module['parts']
    parts = copy.deepcopy(shared[module['source']])
    scale, translation = np.asarray(module['scale']), np.asarray(module['translation'])
    # Normalized anisotropic box scaling is explicit; cylindrical modules use
    # equal X/Z radii and separate authored axial scaling.
    for part in parts:
        for key in ('min','max','start','end'):
            if key in part:
                part[key] = (np.asarray(part[key]) * scale + translation).tolist()
        if 'radius' in part:
            if scale[0] != scale[2]:
                raise ValueError('Circular components require equal radial scale')
            part['radius'] *= scale[0]
    return parts


def export(kit, shared, lod, names, path):
    mesh = components.components.Mesh()
    ranges = []
    for module in kit['modules']:
        if module['name'] not in names:
            continue
        start = len(mesh.indices)
        for part in resolve_parts(module,shared):
            if lod not in part['lods']:
                continue
            kind, cell = part['kind'], part['cell']
            if kind == 'box':
                mesh.box(part['min'],part['max'],cell,part.get('bevel',0) if lod==0 else 0)
            elif kind == 'cylinder':
                mesh.cylinder(part['start'],part['end'],part['radius'],cell,part['sides'][lod])
            elif kind == 'pipe':
                components.pipe(mesh,part,lod)
            elif kind == 'roof':
                roof(mesh,part)
            else:
                raise ValueError(f'Unsupported logistics component: {kind}')
        if len(mesh.indices) > start:
            ranges.append(dict(name=module['name'],parent=module.get('parent'),sharedModule=module.get('source'),firstIndex=start,indexCount=len(mesh.indices)-start))
    positions = np.asarray(mesh.positions)
    if not len(positions) or not np.isfinite(positions).all():
        raise ValueError('Empty or non-finite logistics mesh')
    if np.any(positions.min(0)<np.asarray(kit['bounds']['min'])-1e-5) or np.any(positions.max(0)>np.asarray(kit['bounds']['max'])+1e-5):
        raise ValueError(f'Component exceeds declared bounds: {positions.min(0)}, {positions.max(0)}')
    report = mesh.export(path)
    data = json.loads(path.read_text(encoding='utf-8'))
    data['asset']['generator'] = 'ForgeLine logistics building component exporter'
    data['extras'] = dict(coordinates=kit['coordinates'],componentHierarchy=ranges,anchors=kit['anchors'])
    path.write_text(json.dumps(data,indent=2)+'\n',encoding='utf-8')
    report['sha256'] = hashlib.sha256(path.read_bytes()).hexdigest()
    return report


def author(family, output):
    kit = json.loads((SOURCE/'authoring'/f'{family}.kit.json').read_text(encoding='utf-8'))
    shared = json.loads((SOURCE/'authoring/logistics.modules.json').read_text(encoding='utf-8'))['modules']
    reports = {}
    for lod in range(3):
        reports[f'lod{lod}'] = export(kit,shared,lod,kit['intactModules'],output/f'lod{lod}.gltf')
    for name, modules in kit['states'].items():
        reports[name] = export(kit,shared,1,modules,output/f'{name}.gltf')
    for module in kit['modules']:
        reports['kit/'+module['name']] = export(kit,shared,0,[module['name']],output/'kit'/f"{module['name']}.gltf")
    (output/'exports.json').write_text(json.dumps(reports,indent=2)+'\n',encoding='utf-8')
    print(family,json.dumps({name:value['triangles'] for name,value in reports.items() if not name.startswith('kit/')}))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--family',choices=FAMILIES,action='append')
    parser.add_argument('--output',type=Path,default=SOURCE/'sources/logistics')
    args = parser.parse_args()
    for family in args.family or FAMILIES:
        author(family,args.output/family)
